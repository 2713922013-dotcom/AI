def detect_family(target_position="", skills=None, jd_text=""):
    """判断岗位族。

    目标岗位名优先级最高——用户明确说要投「数据分析师」，就不能因为简历里
    写过运营经历就出成运营岗的题。岗位名没有信号时才看 JD 和技能。
    """
    def best_match(haystack):
        best, score = None, 0
        for family, keywords in FAMILY_KEYWORDS.items():
            # 按命中关键词的总长度计分，越具体的词权重越高（数据运营 > 运营）
            hits = sum(len(kw) for kw in keywords if kw in haystack)
            if hits > score:
                best, score = family, hits
        return best

    pos = (target_position or "").lower().strip()
    if pos:
        matched = best_match(pos)
        if matched:
            return matched

    haystack = " ".join([pos, jd_text or "", " ".join(skills or [])]).lower()
    if not haystack.strip():
        return "general"
    return best_match(haystack) or "general"
